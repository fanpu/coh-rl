#!/usr/bin/env python3
"""Scrape real CoH1 stats from the coh-stats.com mirror into coh/data/tables/.

Run with `uv run python tools/scrape_coh_stats.py`. Fetched HTML is cached under
`tools/.cache/` (git-ignored); a second run is offline and byte-identical.

Inputs
    tools/roster.yaml       which pages are in scope, plus the handful of facts
                            the mirror does not state (weapon counts per squad,
                            building footprints, tech prerequisites)
    tools/patch_2602.yaml   forward-port of the official 2.602 release notes;
                            each entry's `old` is asserted against the scrape

Outputs (overwritten)
    coh/data/tables/weapons.yaml
    coh/data/tables/squads.yaml
    coh/data/tables/buildings.yaml
    coh/data/tables/upgrades.yaml

`economy.yaml` and `neutral.yaml` are hand-written (the mirror carries no
resource, territory or ambient-building data) and are not touched here.

Page anatomy, learned by inspection and relied on below:
  * Every unit/structure/upgrade page opens with one "stat block" table whose
    first row is a single <th> spanning the table; the rest is <th>label</th>
    <td>value</td> pairs, some with rowspan for the L/M/S range bands.
  * Costs are icon-separated: an <img src=".../Manpower.png"> precedes the
    manpower figure, etc. Never parse a cost from stripped text.
  * Weapon pages add a 12-row "Cover Table" and a 53-row "Target Table", both
    <table class="sortable">, identical in shape across all weapons.
  * Section bodies ("Constructs", "Upgrades", "Can Construct", ...) follow an
    <a name="..."></a><h2> anchor and link to the member pages.
"""

