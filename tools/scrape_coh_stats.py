# --- squads -----------------------------------------------------------------------


def parse_squad(
    soup: BeautifulSoup,
    squad_id: str,
    spec: dict[str, Any],
    suppression: dict[tuple[str, str], Flow],
    entities: dict[str, dict[str, str]],
    estimated: dict[str, str],
) -> dict[str, Any]:
    block = stat_block(soup)
    kind = spec["kind"]
    faction = spec["faction"]
    entity_ref = spec.get("entity")
    entity = entities.get(entity_ref, {}) if entity_ref else {}

    loadout = FlowList()
    for weapon_id, count in spec["loadout"]:
        loadout.extend([weapon_id] * int(count))

    if kind == "vehicle":
        members = 1
        member_hp = tidy(numbers(block.text("Health"))[0])
        speed = tidy(numbers(block.text("Max Speed"))[0])
        rotation = tidy(numbers(block.text("Rotation"))[0])
        crushes = bool(entity.get("pass_type"))
        record_suppression = None
        capture_rate: float | int = 0
        reinforce_cost_mult: float | int = 0
        reinforce_time_mult: float | int = 0
        retreat_accuracy: float | int = 1
        upgrade_slots = 0
    else:
        # Towed guns live in the Vehicle: namespace and describe their crew
        # separately from the gun; infantry pages describe the squad directly.
        if block.text("Squad Size") is not None:
            # Infantry pages: "Health" is the whole squad's pool.
            members = int(numbers(block.text("Squad Size"))[0])
            member_hp = tidy(numbers(block.text("Health"))[0] / members)
        elif block.text("Crew Size") is not None:
            # Towed-gun pages: "Crew Health" is already per crew model, and
            # "Health" belongs to the gun itself (not modelled).
            members = int(numbers(block.text("Crew Size"))[0])
            member_hp = tidy(numbers(block.text("Crew Health"))[0])
            estimated[f"{squad_id}.member_hp"] = (
                "Crew health per model, taken as-is. The gun platform's own "
                f"{tidy(numbers(block.text('Health'))[0])} hit points are dropped: SquadDef has "
                "no separate weapon-platform pool, so killing the crew kills the gun."
            )
        else:
            raise ScrapeError(f"{squad_id}: no squad size / crew size on the page")
        speed = tidy(float(entity.get("speed_max", 3.0)))
        rotation = tidy(float(entity.get("rotation_rate", 150.0)))
        crushes = False
        upgrade_slots = int(optional_number(block, "Squad Slots", 0))

        suppression_key = spec.get("suppression_key")
        if suppression_key:
            record_suppression = suppression.get((faction, suppression_key))
            if record_suppression is None:
                raise ScrapeError(f"{squad_id}: no Info:Suppression row for {suppression_key!r}")
        else:
            record_suppression = Flow(STANDARD_INFANTRY_SUPPRESSION)
            estimated[f"{squad_id}.suppression"] = (
                "Info:Suppression has no row for towed guns; standard infantry thresholds assumed."
            )

        if block.text("Capture Rate") is None:
            capture_rate = 0
            estimated[f"{squad_id}.capture_rate"] = (
                "Towed-gun pages carry no capture rate; towed guns cannot capture in CoH1."
            )
        else:
            capture_rate = tidy(numbers(block.text("Capture Rate"))[0])

        if block.text("Reinforce Cost") is None:
            reinforce_cost_mult, reinforce_time_mult, retreat_accuracy = 0.5, 1, 0.5
            estimated[f"{squad_id}.reinforce_cost_mult"] = (
                "Towed-gun pages carry no reinforce/retreat modifiers; the other team "
                "weapons' values (0.5 cost, 1.0 time, 0.5 received accuracy) assumed."
            )
        else:
            reinforce_cost_mult = tidy(numbers(block.text("Reinforce Cost"))[0])
            reinforce_time_mult = tidy(numbers(block.text("Reinforce Time"))[0])
            retreat_accuracy = tidy(numbers(block.text("Retreat Modifier"))[0])

    if kind != "vehicle" and "speed_max" not in entity:
        estimated[f"{squad_id}.speed"] = (
            f"omgmod entities.json has no speed for {entity_ref!r}; 3.0 m/s "
            "(standard infantry) and 150 deg/s assumed."
        )

    return {
        "faction": faction,
        "kind": kind,
        "members": members,
        "member_hp": member_hp,
        "loadout": loadout,
        "target_type": block.text("Target Type"),
        "cost": parse_cost(block.cell("Cost")),
        "population": int(numbers(block.text("Population"))[0]),
        "build_time": tidy(numbers(block.text("Time"))[0]),
        "upkeep_per_min": tidy(numbers(block.text("Upkeep"))[0]),
        "speed": speed,
        "rotation_deg_s": rotation,
        "sight": tidy(numbers(block.text("Sight"))[0]),
        "capture_rate": capture_rate,
        "builds": FlowList(spec.get("builds", [])),
        "suppression": record_suppression,
        "reinforce_cost_mult": reinforce_cost_mult,
        "reinforce_time_mult": reinforce_time_mult,
        "retreat_received_accuracy": retreat_accuracy,
        "upgrade_slots": upgrade_slots,
        "crushes_light_cover": crushes,
        "can_garrison": bool(spec.get("can_garrison", False)),
    }


# --- buildings / upgrades ---------------------------------------------------------


def parse_building(
    soup: BeautifulSoup,
    spec: dict[str, Any],
    squad_by_page: dict[str, str],
    upgrade_by_page: dict[str, str],
) -> dict[str, Any]:
    block = stat_block(soup)
    page_sections = sections(soup)
    produces = [squad_by_page[p] for p in page_sections.get("Constructs", []) if p in squad_by_page]
    researches = [upgrade_by_page[p] for p in page_sections.get("Upgrades", []) if p in upgrade_by_page]
    return {
        "faction": spec["faction"],
        "cost": parse_cost(block.cell("Cost")),
        "build_time": tidy(numbers(block.text("Time"))[0]),
        "hp": tidy(numbers(block.text("Health"))[0]),
        "target_type": block.text("Target Type"),
        "footprint": FlowList(int(x) for x in spec["footprint"]),
        "produces": FlowList(produces),
        "researches": FlowList(researches),
        "requires": FlowList(spec["requires"]),
        "is_hq": bool(spec["is_hq"]),
        "reinforce_radius": optional_number(block, "Reinforce Radius", 0),
        "sight": tidy(numbers(block.text("Sight"))[0]),
    }


def parse_upgrade(soup: BeautifulSoup, spec: dict[str, Any]) -> dict[str, Any]:
    block = stat_block(soup)
    record = {
        "faction": spec["faction"],
        "cost": parse_cost(block.cell("Cost")),
        "time": tidy(numbers(block.text("Time"))[0]),
        "requires": FlowList(spec["requires"]),
    }
    if "upkeep_mult" in spec:
        record["upkeep_mult"] = spec["upkeep_mult"]
    return record


def parse_squad_upgrade(soup: BeautifulSoup, spec: dict[str, Any]) -> dict[str, Any]:
    block = stat_block(soup)
    return {
        "applies_to": FlowList(spec["applies_to"]),
        "cost": parse_cost(block.cell("Cost")),
        "time": tidy(numbers(block.text("Time"))[0]),
        "requires": FlowList(spec["requires"]),
        "weapon": spec["weapon"],
        "count": int(spec["count"]),
    }


# --- 2.602 patching ---------------------------------------------------------------


def apply_patch(tables: dict[str, dict[str, Any]], patches: list[dict[str, Any]]) -> None:
    """Apply each `{table, id, field, old, new}`, asserting `old` first."""
    for patch in patches:
        table_name, entry_id, field = patch["table"], patch["id"], patch["field"]
        table = tables.get(table_name)
        if table is None or entry_id not in table:
            raise ScrapeError(f"patch target {table_name}:{entry_id} was not scraped")
        container: Any = table[entry_id]
        keys = field.split(".")
        for key in keys[:-1]:
            container = _descend(container, key, f"{table_name}:{entry_id}:{field}")
        leaf = keys[-1]
        index = _key_or_index(container, leaf, f"{table_name}:{entry_id}:{field}")
        actual = container[index]
        if abs(float(actual) - float(patch["old"])) > 1e-9:
            raise ScrapeError(
                f"patch {table_name}:{entry_id}:{field} expected old value {patch['old']}, "
                f"scraped {actual}"
            )
        container[index] = tidy(float(patch["new"]))


def _descend(container: Any, key: str, where: str) -> Any:
    return container[_key_or_index(container, key, where)]


def _key_or_index(container: Any, key: str, where: str) -> Any:
    if isinstance(container, list):
        if key not in BAND_NAMES:
            raise ScrapeError(f"patch {where}: {key!r} is not a range band")
        return BAND_NAMES.index(key)
    if key not in container:
        raise ScrapeError(f"patch {where}: no field {key!r}")
    return key


# --- main -------------------------------------------------------------------------


def build_tables(fetcher: Fetcher, roster: dict[str, Any]) -> dict[str, tuple[dict, dict]]:
    """Scrape everything. Returns {table name: (body, estimated notes)}."""
    target_types = roster["target_types"]
    squad_specs = roster["squads"]
    squad_by_page = {spec["page"]: sid for sid, spec in squad_specs.items()}
    upgrade_by_page = {spec["page"]: uid for uid, spec in roster["upgrades"].items()}

    entities = parse_entities(fetcher.json_url(OMG_ENTITIES_URL, OMG_ENTITIES_CACHE))
    suppression = parse_suppression(content_soup(fetcher.page("Info_Suppression")))

    # Weapons carried by foot infantry rotate freely, so their traverse is not a
    # firing arc; team weapons and vehicle mounts keep the page's traverse.
    free_aiming: set[str] = set()
    for spec in squad_specs.values():
        if spec["kind"] == "infantry":
            free_aiming.update(weapon for weapon, _ in spec["loadout"] if weapon)
    for spec in roster["squad_upgrades"].values():
        if all(squad_specs[s]["kind"] == "infantry" for s in spec["applies_to"]):
            free_aiming.add(spec["weapon"])

    weapons: dict[str, Any] = {}
    weapons_estimated: dict[str, str] = {
        "*.cover_table": (
            "The page's 'Open' cover row (accuracy 1.25) is a distinct cover type that "
            "coh-stats' own Info:Weapon Statistics records as unused in game, so it is "
            "not emitted; our `open` (= no cover) falls back to the identity mods, which "
            "equal the page's 'Default' row (1/1/1) for every weapon scraped."
        ),
        "*.cover_table.penetration": (
            "The page's cover table has a penetration column (e.g. 37 mm Greyhound vs "
            "heavy cover 0.5); CoverMods has no penetration field, so it is dropped."
        ),
        "*.damage": "Pages give a min-max damage pair; the mean is used (equal for all but flame weapons).",
        "*.rate_of_fire": "Single-shot weapons list 0 bullets/s; 1 bullet per firing cycle is used instead.",
    }
    traverses: dict[str, float] = {}
    for weapon_id, spec in roster["weapons"].items():
        soup = content_soup(fetcher.page(spec["page"]))
        record, traverse = parse_weapon(soup, spec, target_types)
        traverses[weapon_id] = traverse
        weapons[weapon_id] = record
        if spec.get("indirect"):
            weapons_estimated[f"{weapon_id}.scatter_m"] = (
                "Derived as the page's Scatter Max x Scatter Ratio; the source models "
                "scatter as an angle plus distance ratio, not a metre standard deviation."
            )

    for weapon_id, record in weapons.items():
        if weapon_id in free_aiming:
            record["arc_deg"] = 360
        else:
            record["arc_deg"] = tidy(traverses[weapon_id])

    squads: dict[str, Any] = {}
    squads_estimated: dict[str, str] = {
        "*.loadout": (
            "Squad pages list which weapons a squad carries but not how many of each; "
            "the per-weapon counts come from tools/roster.yaml."
        ),
    }
    for squad_id, spec in squad_specs.items():
        soup = content_soup(fetcher.page(spec["page"]))
        squads[squad_id] = parse_squad(soup, squad_id, spec, suppression, entities, squads_estimated)
        if spec["kind"] == "vehicle":
            squads_estimated.setdefault(
                "*.retreat_received_accuracy (vehicles)",
                "Vehicle pages carry no retreat modifier; vehicles do not retreat, so 1.0 is used.",
            )

    buildings: dict[str, Any] = {}
    buildings_estimated = {
        "*.footprint": "The mirror carries no building dimensions; footprints are authored in tools/roster.yaml.",
        "*.requires": (
            "Prerequisites are not on the structure pages except Supply Yard's "
            "'Barracks OR Weapons Support Center'. `requires` is all-of, so that OR is "
            "approximated by Barracks. Motor Pool and Tank Depot requiring the Supply "
            "Yard is from the Supply Yard page's Unlocks section, cross-checked on the "
            "fandom wiki. Wehrmacht gating is the Reich HQ phase chain."
        ),
    }
    for building_id, spec in roster["buildings"].items():
        soup = content_soup(fetcher.page(spec["page"]))
        buildings[building_id] = parse_building(soup, spec, squad_by_page, upgrade_by_page)

    upgrades: dict[str, Any] = {}
    for upgrade_id, spec in roster["upgrades"].items():
        soup = content_soup(fetcher.page(spec["page"]))
        upgrades[upgrade_id] = parse_upgrade(soup, spec)

    squad_upgrades: dict[str, Any] = {}
    for upgrade_id, spec in roster["squad_upgrades"].items():
        soup = content_soup(fetcher.page(spec["page"]))
        squad_upgrades[upgrade_id] = parse_squad_upgrade(soup, spec)

    upgrades_estimated = {
        "supply_yard_l1.upkeep_mult": (
            "From the Supply Yard page's effect text ('Decrease the Upkeep cost of your "
            "Troops by 25%'); the mirror has no numeric upkeep field for upgrades."
        ),
        "supply_yard_l2.upkeep_mult": (
            "From 'Decrease the Upkeep cost of your Troops by an additional 25%', applied "
            "multiplicatively on top of level 1."
        ),
        "*.count": (
            "Squad-upgrade pages give cost, time, weapon and eligible squads but not how "
            "many models receive the weapon; counts are authored in tools/roster.yaml."
        ),
    }

    patches = yaml.safe_load(PATCH_PATH.read_text())["patches"]
    apply_patch({"weapons": weapons, "squads": squads}, patches)

    return {
        "weapons": ({"weapons": weapons}, weapons_estimated),
        "squads": ({"squads": squads}, squads_estimated),
        "buildings": ({"buildings": buildings}, buildings_estimated),
        "upgrades": ({"upgrades": upgrades, "squad_upgrades": squad_upgrades}, upgrades_estimated),
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--offline", action="store_true", help="fail instead of fetching uncached pages")
    args = parser.parse_args(argv)

    roster = yaml.safe_load(ROSTER_PATH.read_text())
    fetcher = Fetcher(roster["source_base"], offline=args.offline)
    try:
        tables = build_tables(fetcher, roster)
    except ScrapeError as exc:
        print(f"scrape failed: {exc}", file=sys.stderr)
        return 1

    TABLES_DIR.mkdir(parents=True, exist_ok=True)
    for name, (body, estimated) in tables.items():
        path = TABLES_DIR / f"{name}.yaml"
        write_table(path, SOURCE_LINE, estimated, body)
        count = sum(len(v) for v in body.values())
        print(f"wrote {path.relative_to(TABLES_DIR.parents[2])} ({count} entries)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
