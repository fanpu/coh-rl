class ScrapeError(RuntimeError):
    """Raised when a page cannot be parsed or a patch precondition fails."""


# --- YAML output shaping ----------------------------------------------------------


class Flow(dict):
    """A mapping rendered on one line, for small records like `{manpower: 270}`."""


class FlowList(list):
    """A sequence rendered on one line, for tuples like `[8, 17, 35]`."""


yaml.SafeDumper.add_representer(
    Flow, lambda dumper, data: dumper.represent_mapping("tag:yaml.org,2002:map", data, flow_style=True)
)
yaml.SafeDumper.add_representer(
    FlowList, lambda dumper, data: dumper.represent_sequence("tag:yaml.org,2002:seq", data, flow_style=True)
)


def write_table(path: Path, source: str, estimated: dict[str, str], body: dict[str, Any]) -> None:
    doc: dict[str, Any] = {"source": source}
    if estimated:
        doc["estimated"] = estimated
    doc.update(body)
    text = yaml.safe_dump(doc, sort_keys=False, default_flow_style=False, width=100, allow_unicode=True)
    path.write_text(FILE_BANNER + text)


# --- fetching ---------------------------------------------------------------------


class Fetcher:
    """Fetches pages once, then serves them from `tools/.cache/`."""

    def __init__(self, base: str, *, offline: bool = False) -> None:
        self.base = base
        self.offline = offline
        self._last_request = 0.0
        CACHE_DIR.mkdir(parents=True, exist_ok=True)

    def _download(self, url: str, dest: Path) -> str:
        if self.offline:
            raise ScrapeError(f"{dest.name} not cached and --offline was given")
        wait = REQUEST_INTERVAL_S - (time.monotonic() - self._last_request)
        if wait > 0:
            time.sleep(wait)
        try:
            response = requests.get(url, headers={"User-Agent": USER_AGENT}, timeout=30)
            response.raise_for_status()
        except requests.RequestException as exc:  # pragma: no cover - network
            raise ScrapeError(f"could not fetch {url}: {exc}") from exc
        self._last_request = time.monotonic()
        dest.write_text(response.text, encoding="utf-8", errors="replace")
        return response.text

    def page(self, name: str) -> str:
        """Fetch a mirror page by its `Infantry_Riflemen` style name."""
        dest = CACHE_DIR / f"{name}.html"
        if dest.exists():
            return dest.read_text(encoding="utf-8", errors="replace")
        return self._download(f"{self.base}{name}.html", dest)

    def json_url(self, url: str, cache_name: str) -> Any:
        dest = CACHE_DIR / cache_name
        if not dest.exists():
            self._download(url, dest)
        return json.loads(dest.read_text(encoding="utf-8", errors="replace"))


# --- HTML helpers -----------------------------------------------------------------


def content_soup(html: str) -> BeautifulSoup:
    """Return the page body, stripped of the mirror's chrome and scripts."""
    start = html.find("<!-- start content -->")
    end = html.find("printfooter")
    if start < 0 or end < 0:
        raise ScrapeError("page has no recognisable content region")
    soup = BeautifulSoup(html[start:end], "html.parser")
    for script in soup.find_all("script"):
        script.decompose()
    return soup


Cell = tuple[Tag, bool, int]  # (cell, is_origin, rowspan)


def table_grid(table: Tag) -> dict[tuple[int, int], Cell]:
    """Expand a table into {(row, col): cell}, replicating row/colspan cells."""
    grid: dict[tuple[int, int], Cell] = {}
    rows = table.find_all("tr", recursive=False) or table.find_all("tr")
    for r, tr in enumerate(rows):
        c = 0
        for cell in tr.find_all(["td", "th"], recursive=False):
            while (r, c) in grid:
                c += 1
            rowspan = int(cell.get("rowspan", 1))
            colspan = int(cell.get("colspan", 1))
            for dr in range(rowspan):
                for dc in range(colspan):
                    grid[(r + dr, c + dc)] = (cell, dr == 0 and dc == 0, rowspan)
            c += colspan
    return grid


def cell_text(cell: Tag) -> str:
    return " ".join(cell.get_text(" ", strip=True).split())


class StatBlock:
    """The label/value table at the top of a unit, structure or upgrade page.

    Scalar labels resolve to the cell to their right. Labels with rowspan N (the
    L/M/S range bands) resolve to N (letter, value) pairs.
    """

    def __init__(self, table: Tag) -> None:
        self.table = table
        self.grid = table_grid(table)
        self.rows = max(r for r, _ in self.grid) + 1
        self.cols = max(c for _, c in self.grid) + 1
        self._labels: dict[str, tuple[int, int, int]] = {}
        for r in range(self.rows):
            for c in range(self.cols):
                entry = self.grid.get((r, c))
                if entry and entry[1] and entry[0].name == "th":
                    label = cell_text(entry[0])
                    if label and label not in self._labels:
                        self._labels[label] = (r, c, entry[2])

    def _locate(self, label: str) -> tuple[int, int, int] | None:
        if label in self._labels:
            return self._labels[label]
        for text, position in self._labels.items():
            if text.startswith(label + " "):  # e.g. "Range Max:35 Min:0"
                return position
        return None

    def label_text(self, label: str) -> str | None:
        position = self._locate(label)
        if position is None:
            return None
        row, col, _ = position
        return cell_text(self.grid[(row, col)][0])

    def cell(self, label: str) -> Tag | None:
        position = self._locate(label)
        if position is None:
            return None
        row, col, _ = position
        entry = self.grid.get((row, col + 1))
        return entry[0] if entry else None

    def text(self, label: str) -> str | None:
        cell = self.cell(label)
        return cell_text(cell) if cell is not None else None

    def bands(self, label: str) -> dict[str, str]:
        """Read an L/M/S band group into {letter: value}."""
        position = self._locate(label)
        if position is None:
            raise ScrapeError(f"missing band label {label!r}")
        row, col, rowspan = position
        out: dict[str, str] = {}
        for i in range(rowspan):
            letter = self.grid.get((row + i, col + 1))
            value = self.grid.get((row + i, col + 2))
            if letter is None or value is None:
                continue
            out[cell_text(letter[0])] = cell_text(value[0])
        missing = set(BAND_LETTERS) - set(out)
        if missing:
            raise ScrapeError(f"band label {label!r} is missing bands {sorted(missing)}")
        return out


def stat_block(soup: BeautifulSoup) -> StatBlock:
    """The first table whose header row is one <th> spanning the whole table."""
    for table in soup.find_all("table"):
        rows = table.find_all("tr", recursive=False)
        if not rows:
            continue
        cells = rows[0].find_all(["td", "th"], recursive=False)
        if len(cells) == 1 and cells[0].name == "th" and int(cells[0].get("colspan", 1)) >= 3:
            return StatBlock(table)
    raise ScrapeError("page has no stat block table")


def sections(soup: BeautifulSoup) -> dict[str, list[str]]:
    """{section anchor name: linked page names}, for the page's <h2> sections."""
    html = str(soup)
    anchors = [(m.start(), m.group(1)) for m in re.finditer(r'<a name="([^"]+)"></a><h2>', html)]
    out: dict[str, list[str]] = {}
    for index, (position, name) in enumerate(anchors):
        end = anchors[index + 1][0] if index + 1 < len(anchors) else len(html)
        pages: list[str] = []
        for href in re.findall(r'href="([^"]+\.html)"', html[position:end]):
            page = href[: -len(".html")]
            if page not in pages:
                pages.append(page)
        out[name] = pages
    return out


# --- value helpers ----------------------------------------------------------------

DASH = "—"  # coh-stats writes ranges as "min—max"


def numbers(text: str | None) -> list[float]:
    """The numbers in a cell like `3.5—2.5`, `-60—60` or `87.5`."""
    if text is None:
        raise ScrapeError("expected a numeric cell, found none")
    found = re.findall(r"-?\d+(?:\.\d+)?", text)
    if not found:
        raise ScrapeError(f"no number in {text!r}")
    return [float(x) for x in found]


INTEGER_SNAP_MIN = 5.0
INTEGER_SNAP_TOLERANCE = 0.05


def tidy(value: float) -> float | int:
    """Round away the mirror's float noise (260.01 -> 260, 39.99 -> 40).

    Snapping to an integer is only safe for the large quantities that carry the
    noise (costs, times, hit points); small multipliers such as the Engineers'
    0.02 suppression threshold must survive untouched.
    """
    if abs(value) >= INTEGER_SNAP_MIN and abs(value - round(value)) < INTEGER_SNAP_TOLERANCE:
        return int(round(value))
    rounded = round(value, 6)
    return int(rounded) if rounded == int(rounded) else rounded


def optional_number(block: StatBlock, label: str, default: float) -> float | int:
    text = block.text(label)
    if text is None or not text.strip():
        return tidy(default)
    return tidy(numbers(text)[0])


def band_tuple(block: StatBlock, label: str) -> FlowList:
    values = block.bands(label)
    return FlowList(tidy(numbers(values[letter])[0]) for letter in BAND_LETTERS)


def parse_cost(cell: Tag | None) -> Flow:
    """Costs are separated by resource icons, so read the icons, not the text.

    Infantry squad pages are the one exception: they print a bare manpower figure
    with no icon at all (`<th>Cost</th><td>260.01</td>`).
    """
    cost: dict[str, float] = {}
    if cell is None:
        return Flow()
    current: str | None = "manpower" if cell.find("img") is None else None
    for node in cell.descendants:
        if isinstance(node, Tag) and node.name == "img":
            current = RESOURCE_ICONS.get(node.get("src", "").rsplit("/", 1)[-1])
        elif isinstance(node, NavigableString):
            text = str(node).strip()
            if not text or current is None:
                continue
            for value in numbers(text):
                cost[current] = cost.get(current, 0.0) + value
    # Command points gate doctrinal unlocks only; nothing in the roster uses them.
    cost.pop("command_points", None)
    return Flow((key, tidy(value)) for key, value in cost.items() if value)


# --- weapons ----------------------------------------------------------------------


def sortable_tables(soup: BeautifulSoup) -> dict[str, list[list[str]]]:
    """The weapon page's Cover Table and Target Table, keyed by first header."""
    out: dict[str, list[list[str]]] = {}
    for table in soup.find_all("table"):
        classes = table.get("class") or []
        if "sortable" not in classes:
            continue
        rows = [[cell_text(c) for c in tr.find_all(["th", "td"])] for tr in table.find_all("tr")]
        if rows:
            out[rows[0][0]] = rows
    return out


def parse_weapon(soup: BeautifulSoup, spec: dict[str, Any], target_types: dict[str, str]) -> tuple[dict, float]:
    """Return (weapon record, horizontal traverse in degrees)."""
    block = stat_block(soup)

    damage_values = numbers(block.text("Damage"))
    burst_values = numbers(block.text("Burst Duration"))
    rof_values = numbers(block.text("Rate of Fire"))
    reload_frequency = max(numbers(block.text("Reload Frequency")))

    burst = None if max(burst_values) == 0 else FlowList(tidy(v) for v in sorted(burst_values))
    rate_of_fire = tidy(max(rof_values))
    if burst is None and rate_of_fire == 0:
        # Single-shot weapon: one bullet per firing cycle.
        rate_of_fire = 1

    range_label = block.label_text("Range") or ""
    min_range_match = re.search(r"Min:\s*(-?\d+(?:\.\d+)?)", range_label)
    if min_range_match is None:
        raise ScrapeError(f"no minimum range in {range_label!r}")

    record: dict[str, Any] = {
        "damage": tidy(sum(damage_values) / len(damage_values)),
        "ranges": band_tuple(block, "Range"),
        "min_range": tidy(float(min_range_match.group(1))),
        "accuracy": band_tuple(block, "Accuracy"),
        "penetration": band_tuple(block, "Penetration"),
        "suppression": band_tuple(block, "Suppression"),
        "cooldown": FlowList(tidy(v) for v in sorted(numbers(block.text("Cooldown")))),
        "cooldown_range_mult": band_tuple(block, "Cooldown Multiplier"),
        "burst": burst,
        "rate_of_fire": rate_of_fire,
        "reload": FlowList(tidy(v) for v in sorted(numbers(block.text("Reload")))),
        # "The actual clip size is Reload Frequency + 1"; 0 means "reload every shot".
        "reload_every": max(1, int(reload_frequency)),
        "setup_time": tidy(numbers(block.text("Setup Time"))[0]),
        "moving_accuracy": tidy(numbers(block.text("Moving Accuracy"))[0]),
        "nearby_suppression_mult": tidy(numbers(block.text("Nearby Supp. Multiplier"))[0]),
        "nearby_suppression_radius": tidy(numbers(block.text("Nearby Supp. Radius"))[0]),
        "aoe_radius": tidy(numbers(block.bands("AOE Distance")["L"])[0]),
        "deflection_damage_mult": tidy(numbers(block.text("Deflection Multiplier"))[0]),
    }

    if spec.get("indirect"):
        scatter_max = numbers(block.text("Scatter Max"))[0]
        scatter_ratio = numbers(block.text("Scatter Ratio"))[0]
        record["indirect"] = True
        record["scatter_m"] = tidy(scatter_max * scatter_ratio)

    tables = sortable_tables(soup)
    cover_rows = tables.get("Cover Type")
    target_rows = tables.get("Target Name")
    if cover_rows is None or target_rows is None:
        raise ScrapeError("weapon page is missing its cover or target table")

    cover_table: dict[str, Flow] = {}
    for row in cover_rows[1:]:
        key = COVER_ROWS.get(row[0])
        if key is None:
            continue
        accuracy, damage, suppression = (float(row[1]), float(row[2]), float(row[3]))
        cover_table[key] = Flow(
            accuracy=tidy(accuracy), damage=tidy(damage), suppression=tidy(suppression)
        )
    if set(cover_table) != set(COVER_ROWS.values()):
        raise ScrapeError(f"cover table is missing rows: {sorted(set(COVER_ROWS.values()) - set(cover_table))}")

    target_table: dict[str, Flow] = {}
    for row in target_rows[1:]:
        key = target_types.get(row[0])
        if key is None:
            continue
        target_table[key] = Flow(
            accuracy=tidy(float(row[1])),
            moving=tidy(float(row[2])),
            damage=tidy(float(row[3])),
            penetration=tidy(float(row[4])),
            rear_penetration=tidy(float(row[5])),
            suppression=tidy(float(row[6])),
            priority=tidy(float(row[7])),
        )
    missing_targets = set(target_types.values()) - set(target_table)
    if missing_targets:
        raise ScrapeError(f"target table is missing rows: {sorted(missing_targets)}")

    record["cover_table"] = cover_table
    record["target_table"] = target_table

    traverse = numbers(block.text("Tracking Horizontal"))
    return record, max(traverse) - min(traverse)


# --- suppression ------------------------------------------------------------------

SUPPRESSION_HEADER = ["Units", "SAT", "SRT", "PAT", "PRT", "Rec Rate"]
SUPPRESSION_FACTIONS = ("us", "wehr")  # page order: American, Wehrmacht, CW, PE


def parse_suppression(soup: BeautifulSoup) -> dict[tuple[str, str], Flow]:
    """{(faction, unit name): suppression record} from Info:Suppression."""
    out: dict[tuple[str, str], Flow] = {}
    index = 0
    for table in soup.find_all("table"):
        rows = [[cell_text(c) for c in tr.find_all(["th", "td"])] for tr in table.find_all("tr")]
        if not rows or rows[0] != SUPPRESSION_HEADER:
            continue
        if index >= len(SUPPRESSION_FACTIONS):
            break
        faction = SUPPRESSION_FACTIONS[index]
        index += 1
        for row in rows[1:]:
            if len(row) != 6:
                continue
            out[(faction, row[0])] = Flow(
                suppress_at=tidy(float(row[1])),
                suppress_recover=tidy(float(row[2])),
                pin_at=tidy(float(row[3])),
                pin_recover=tidy(float(row[4])),
                recovery_per_s=float(row[5]),
            )
    if index < len(SUPPRESSION_FACTIONS):
        raise ScrapeError("Info:Suppression is missing the American or Wehrmacht threshold table")
    return out


